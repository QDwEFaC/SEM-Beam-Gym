"""Не-RL стратегии коррекции: нулевая и линейная прямая компенсация по датчикам.

Линейный компенсатор - классический подход к активному шумоподавлению: команда коррекции
есть линейная комбинация последних HIST отсчётов магнитометра и акселерометра (и фазы сети).
Коэффициенты подбираются гребневой регрессией по эпизодам без коррекции, где известно истинное
смещение луча - те же привилегированные данные симулятора, что и в награде RL.
Фильтр подгоняется под тот же сценарий, на котором обучается RL-агент.

Это "простой ориентир", который требует трек 2 задания: эвристическая (нулевая) и классическая
инженерная стратегии. 
Линейный фильтр, обученый с учителем на привилегированных данных, мог бы
служить экспертом для BC/DAgger. Этот вариант НЕ реализован!
"""

from __future__ import annotations

import numpy as np

from sem_beam_gym.env import SUB, U_MAX, BeamEnv
from sem_beam_gym.scenarios import Scenario


class ZeroPolicy:
    """Без коррекции."""

    def act(self, obs):
        """Нулевая коррекция при любом наблюдении."""
        # Это нижняя граница, от которой считается любой выигрыш.
        return np.zeros(1, dtype=np.float32)


class LinearPolicy:
    """Линейный компенсатор: команда = w (фаза сети, датчики, 1)."""

    def __init__(self, w: np.ndarray, env: BeamEnv):
        # Хранятся только веса и срезы наблюдения, поэтому политика работает с наблюдением той же
        # среды, что и RL-агент, и оценивается той же процедурой.
        self.w, self.idx = w, (env.idx_phase, env.idx_sensors)

    @staticmethod
    def features(obs: np.ndarray, idx) -> np.ndarray:
        """Признаки фильтра из наблюдения: фаза сети, история датчиков и свободный член."""
        # Фильтр видит ровно те же 16 шагов датчиков, что и агент - сравнение честное.
        # История своих действий и сдвиги строк не берутся: это прямая компенсация (feedforward),
        # как в классическом активном шумоподавлении.
        obs = np.atleast_2d(obs)
        return np.hstack([obs[:, idx[0]], obs[:, idx[1]], np.ones((len(obs), 1))])

    def act(self, obs):
        """Предсказанное смещение луча как команда коррекции, в долях U_MAX."""
        # Ограничение [-1, 1] то же, что у среды, чтобы фильтр не получал преимущества.
        return np.clip(self.features(obs, self.idx) @ self.w / U_MAX, -1, 1).astype(np.float32).ravel()

    @classmethod
    def fit(cls, scenario: Scenario | str, n_episodes=200, seed=200_000, ridge=1e-2):
        """Подогнать веса гребневой регрессией на эпизодах без коррекции."""
        # Собираются пары (наблюдение, смещение луча на следующем шаге) и решается
        # (F^T F + ridge * I) w = F^T y - лучший линейный фильтр для сценария обучения, сильный
        # инженерный бейзлайн. Без коррекции наблюдение не зависит от политики, поэтому задача
        # сводится к обычной регрессии с точным решением. Малый ridge стабилизирует обращение при
        # коррелированных соседних отсчётах. Seed 200 000+ не пересекаются с тестом.
        env = BeamEnv(sensors=True, scenario=scenario)
        X, y = [], []
        for i in range(n_episodes):
            obs, _ = env.reset(seed=seed + i)
            done = False
            while not done:
                k = env.k
                X.append(obs)
                y.append(env.d[k * SUB : (k + 1) * SUB].mean())  # смещение на следующем шаге
                obs, _, _, done, _ = env.step(np.zeros(1))
        F = cls.features(np.array(X), (env.idx_phase, env.idx_sensors))
        w = np.linalg.solve(F.T @ F + ridge * np.eye(F.shape[1]), F.T @ np.array(y))
        return cls(w, env)
